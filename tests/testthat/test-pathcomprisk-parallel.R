test_that("PSOCK execution is reproducible and leaves no owned backend", {
  skip_on_cran()
  args <- make_path_case(3)
  a <- run_with_raw_draws(args, "hazard", 416, nboot = 3L, ncores = 2L)
  b <- run_with_raw_draws(args, "hazard", 416, nboot = 3L, ncores = 2L)
  expect_identical(a$raw, b$raw)
  expect_identical(a$summary, b$summary)
  expect_identical(foreach::getDoParName(), "doSEQ")
  cl <- parallel::makePSOCKcluster(2L)
  on.exit({ parallel::stopCluster(cl); foreach::registerDoSEQ() }, add = TRUE)
  doParallel::registerDoParallel(cl)
  external <- run_with_raw_draws(args, "hazard", 416, nboot = 3L, ncores = 2L)
  expect_identical(a$raw, external$raw)
  expect_identical(foreach::getDoParWorkers(), 2L)
})
